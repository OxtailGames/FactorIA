// Android backend of the VFS: project files are packaged as APK assets and read
// through AAssetManager. Compiled only on Android (see the _android suffix rule).
// NOTE: written against <android/asset_manager.h> but not exercised by desktop CI.
#include <android/asset_manager.h>

#include <atomic>
#include <set>

#include "fa/core/fs.h"
#include "fs_internal.h"

namespace fa::fs {
namespace {
std::atomic<AAssetManager*> g_manager{nullptr};
}

void set_android_asset_manager(void* aassetManager) { g_manager = static_cast<AAssetManager*>(aassetManager); }

namespace detail {

bool android_read(const std::string& path, std::vector<std::uint8_t>& out) {
    AAssetManager* mgr = g_manager.load();
    if (!mgr) return false;
    AAsset* asset = AAssetManager_open(mgr, path.c_str(), AASSET_MODE_BUFFER);
    if (!asset) return false;
    off_t len = AAsset_getLength(asset);
    out.resize(len > 0 ? std::size_t(len) : 0);
    const void* buf = AAsset_getBuffer(asset);
    if (buf && len > 0) {
        out.assign(static_cast<const std::uint8_t*>(buf), static_cast<const std::uint8_t*>(buf) + len);
    } else if (len > 0) {
        // Compressed asset without a direct buffer: fall back to read().
        int n = AAsset_read(asset, out.data(), std::size_t(len));
        if (n < 0) { AAsset_close(asset); return false; }
        out.resize(std::size_t(n));
    }
    AAsset_close(asset);
    return true;
}

bool android_exists(const std::string& path) {
    AAssetManager* mgr = g_manager.load();
    if (!mgr) return false;
    if (AAsset* a = AAssetManager_open(mgr, path.c_str(), AASSET_MODE_UNKNOWN)) {
        AAsset_close(a);
        return true;
    }
    return android_is_directory(path);
}

bool android_is_directory(const std::string& path) {
    AAssetManager* mgr = g_manager.load();
    if (!mgr) return false;
    AAssetDir* dir = AAssetManager_openDir(mgr, path.c_str());
    if (!dir) return false;
    bool any = AAssetDir_getNextFileName(dir) != nullptr;  // openDir succeeds for nonexistent dirs, so check content
    AAssetDir_close(dir);
    return any;
}

std::vector<std::string> android_list(const std::string& dir, bool recursive) {
    std::vector<std::string> out;
    AAssetManager* mgr = g_manager.load();
    if (!mgr) return out;
    // AAssetDir only lists FILES of one directory, never subdirectories, so a recursive listing
    // needs an index. Projects ship "assets/index.txt" (one project-relative path per line,
    // generated by `factoria export`); without it only the top level is listed.
    if (recursive) {
        std::vector<std::uint8_t> index;
        if (android_read("assets_index.txt", index)) {
            std::string text(index.begin(), index.end());
            std::string prefix = dir.empty() ? std::string() : dir + "/";
            std::size_t pos = 0;
            while (pos < text.size()) {
                std::size_t nl = text.find('\n', pos);
                if (nl == std::string::npos) nl = text.size();
                std::string line = text.substr(pos, nl - pos);
                while (!line.empty() && (line.back() == '\r' || line.back() == ' ')) line.pop_back();
                if (!line.empty() && line.compare(0, prefix.size(), prefix) == 0) out.push_back(line);
                pos = nl + 1;
            }
            return out;
        }
    }
    AAssetDir* d = AAssetManager_openDir(mgr, dir.c_str());
    if (!d) return out;
    while (const char* name = AAssetDir_getNextFileName(d)) out.push_back(dir.empty() ? name : dir + "/" + name);
    AAssetDir_close(d);
    return out;
}

}  // namespace detail
}  // namespace fa::fs
