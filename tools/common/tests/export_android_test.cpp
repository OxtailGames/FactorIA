        REQUIRE_MESSAGE(r.ok(), (r.ok() ? "" : r.error().to_string()));
        CHECK(gradle_properties(r->outputDir).find("factoria.cmakeVersion=3.28.3\n") != std::string::npos);
        CHECK(any_contains(r->warnings, "SDK's CMake 3.28.3"));
