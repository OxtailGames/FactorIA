bool contains(const std::string& text, const std::string& what) { return text.find(what) != std::string::npos; }

std::size_t count_of(const std::string& text, const std::string& what) {
    std::size_t n = 0;
    for (std::size_t at = text.find(what); at != std::string::npos; at = text.find(what, at + what.size())) ++n;
    return n;
}

// A game whose factoria.json also holds `iosSettings` under export.ios (an object, or null for none).
std::string make_game(const testing::TempDir& tmp, const Json& iosSettings = Json()) {
    const std::string dir = tmp.sub("proj");
    ScaffoldOptions so;
    so.name = "Space Dodge";
    so.id = "com.example.spacedodge";
    auto r = create_project(dir, "2d-platformer", so);
    REQUIRE_MESSAGE(r.ok(), (r.ok() ? "" : r.error().to_string()));
    if (!iosSettings.is_null()) {
        const std::string file = (stdfs::path(dir) / "factoria.json").generic_string();
        auto project = load_json_file(file);
        REQUIRE(project.ok());
        (*project)["export"]["ios"] = iosSettings;
        testing::write_all(file, dump_json(*project));
    }
    return dir;
}

Result<ExportReport> export_ios(const std::string& proj, const testing::TempDir& tmp) {
    ExportOptions o;
    o.projectDir = proj;
    o.platform = "ios";
    o.outDir = tmp.sub("out");
    const stdfs::path mobile = tmp.sub("download/mobile");
    for (const char* slice : {"iphoneos", "iphonesimulator"}) testing::write_all(mobile / "ios" / slice / "libfactoria_player_main.a", "fake");
    o.mobileDir = mobile.string();
    return export_project(o);
}

// The reasons the manifest gives for `category` (empty when the category is not declared): the <string>s of its
// NSPrivacyAccessedAPITypeReasons array.
std::vector<std::string> reasons_of(const std::string& manifest, const std::string& category) {
    std::vector<std::string> out;
    const std::string marker = "<string>NSPrivacyAccessedAPICategory" + category + "</string>";
    std::size_t at = manifest.find(marker);
    if (at == std::string::npos) return out;
    const std::size_t end = manifest.find("</dict>", at);
    for (std::size_t s = manifest.find("<string>", at + marker.size()); s != std::string::npos && s < end; s = manifest.find("<string>", s + 1)) {
        const std::size_t close = manifest.find("</string>", s);
        out.push_back(manifest.substr(s + 8, close - s - 8));
    }
    return out;
}

std::vector<std::string> error_texts(const ExportSettingsParse& p) {
    std::vector<std::string> out;
    for (const auto& e : p.errors) out.push_back(e.to_string());
    return out;
}

bool any_contains(const std::vector<std::string>& lines, const std::string& what) {
    return std::any_of(lines.begin(), lines.end(), [&](const std::string& l) { return contains(l, what); });
}

