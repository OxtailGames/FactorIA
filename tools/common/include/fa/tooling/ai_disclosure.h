// The AI-generated content disclosure that stores ask for (Steam's "AI generated content" survey), written from the
// provenance records of assets.json (schemas/assets.schema.json). `assets.disclosure` returns it and `factoria export` writes
// it as AI_CONTENT_DISCLOSURE.md next to an exported game that has AI-made assets.
#pragma once

#include <string>
#include <vector>

#include "fa/core/json.h"

namespace fa {

inline constexpr const char* kAiDisclosureFile = "AI_CONTENT_DISCLOSURE.md";

// True when any asset of `manifest` (the parsed assets.json) is recorded as made with AI (provenance.ai).
bool has_ai_content(const Json& manifest);

// Markdown: what is pre-generated by AI, by category (art and images, sound effects, music, voice, 3D models) with the
// counts, providers and models; the statement that nothing is generated at run time; the terms recorded for each provider;
// and the art, sound and model files under assets/ that have no provenance record yet. `assetFiles` are the project-relative
// paths of the files in the project: records of files that are not in it are left out.
std::string ai_content_disclosure(const Json& manifest, const std::vector<std::string>& assetFiles);

// The art, sound and model files among `assetFiles` that live under assets/ and have no provenance record (sorted).
std::vector<std::string> assets_without_provenance(const Json& manifest, const std::vector<std::string>& assetFiles);

}  // namespace fa
