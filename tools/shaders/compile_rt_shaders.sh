#!/usr/bin/env bash
# Regenerates the headers of the engine's ray tracing kernels: engine/render/shaders/rt/<name>.hlsl + <name>.metal ->
# engine/render/src/shaders/rt/<name>.rt.h (docs/design/ARCHITECTURE_RENDERING_RAYTRACING_SHADERS.md). The generated headers are
# committed, so a normal build never needs this script, DXC or the Metal toolchain.
#
#   tools/shaders/compile_rt_shaders.sh            # all kernels
#   tools/shaders/compile_rt_shaders.sh rt_probe   # only these
#   tools/shaders/compile_rt_shaders.sh --check    # writes nothing: exit 1 when a committed header differs (CI, a pre-push look)
#
# A header holds three blobs:
#   dxil   the D3D12 kernel: DXC `-T cs_6_5` of the .hlsl (DXIL, signed by dxil.dll / libdxil.so)
#   spirv  the Vulkan kernel: DXC `-spirv -fspv-target-env=vulkan1.2 -fspv-extension=SPV_KHR_ray_query` of the same .hlsl
#   msl    the Metal kernel: the .metal text as it is (MSL 2.4; the renderer compiles it with MTLDevice at run time)
# DXC is the pinned release of fa/tooling/setup.h (`factoria setup dxc` installs it into
# ${FACTORIA_HOME:-$HOME/.factoria}/tools/dxc/<version>/; $FA_DXC_DIR names a folder of your own). It exists for Windows (x64, arm64) and
# Linux x86_64 only. Where there is none (a Mac), the dxil and spirv blobs of the committed header are kept as they are, the msl blob
# is regenerated, and a .hlsl that changed since those blobs were made is reported as STALE (exit status 2 under --check): commit the
# change and the Linux CI job regenerates the blobs, fails with the diff and uploads the headers as the artifact `rt-shader-headers`.
# The DXIL and the SPIR-V DXC writes are the same bytes on every host (a test of the repository compares the Windows and the Linux ones).
set -euo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC="$ROOT/engine/render/shaders/rt"
OUT="$ROOT/engine/render/src/shaders/rt"
SETUP_H="$ROOT/tools/common/include/fa/tooling/setup.h"

CHECK=0
NAMES=()
for arg in "$@"; do
    case "$arg" in
        --check) CHECK=1 ;;
        -h|--help) sed -n '2,19p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        -*) echo "unknown option $arg (--check, --help)" >&2; exit 1 ;;
        *) NAMES+=("$arg") ;;
    esac
done

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

DXC_VERSION="$(sed -n 's|^inline constexpr const char\* kSetupDxcVersion = "\([^"]*\)";.*|\1|p' "$SETUP_H" | head -n 1)"
if [ -z "$DXC_VERSION" ]; then
    echo "error: kSetupDxcVersion not found in $SETUP_H (the line was reformatted? fix the sed in $0)" >&2
    exit 1
fi

case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) EXE_SUFFIX=".exe" ;; *) EXE_SUFFIX="" ;; esac
find_dxc() {
    local dir="${FA_DXC_DIR:-}" candidate
    if [ -n "$dir" ]; then
        for candidate in "$dir/bin/dxc$EXE_SUFFIX" "$dir/dxc$EXE_SUFFIX"; do
            [ -x "$candidate" ] && { echo "$candidate"; return; }
        done
        echo "error: FA_DXC_DIR=$dir holds no bin/dxc$EXE_SUFFIX: fix the path or unset it" >&2
        exit 1
    fi
    candidate="${FACTORIA_HOME:-$HOME/.factoria}/tools/dxc/$DXC_VERSION/bin/dxc$EXE_SUFFIX"
    [ -x "$candidate" ] && echo "$candidate"
    return 0
}
DXC="$(find_dxc)"
if [ -n "$DXC" ]; then
    if ! "$DXC" --version 2>&1 | grep -q "$DXC_VERSION"; then
        echo "warning: $DXC is not DXC $DXC_VERSION (the pinned version of setup.h); the generated bytes may differ from CI's" >&2
    fi
else
    echo "note: no DXC $DXC_VERSION here (factoria setup dxc; Windows and Linux x86_64 only): the dxil and spirv blobs are kept." >&2
fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/fa-rt-shaders.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

camel() { printf '%s' "$1" | awk -F_ '{ for (i = 1; i <= NF; i++) printf "%s%s", toupper(substr($i, 1, 1)), substr($i, 2) }'; }

# emit_blob <label> <file> <nul>: the blob as a C++ array between the BEGIN/END lines the script and the tests read back.
emit_blob() {
    local label="$1" file="$2" nul="$3" cname="$4"
    printf '// BEGIN %s sha256=%s bytes=%s\n' "$label" "$(sha256_of "$file")" "$(wc -c <"$file" | tr -d ' ')"
    printf 'inline constexpr std::uint8_t %s[] = {\n' "$cname"
    # awk rebuilds each line from od's fields: BSD od pads the bytes, GNU od does not, the header must not depend on it.
    od -An -v -tx1 "$file" | awk 'NF { line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
    [ "$nul" = 1 ] && printf '    0x00,  // the text is NUL-terminated\n'
    printf '};\n// END %s\n' "$label"
}

# section_of <label> <header>: the lines of a blob of an existing header.
section_of() { sed -n "/^\/\/ BEGIN $1 /,/^\/\/ END $1\$/p" "$2"; }
meta_of() { sed -n "s|^// $1: *||p" "$2" | head -n 1; }

stale=0
changed=0
generate() {
    local name="$1" hlsl="$SRC/$1.hlsl" msl="$SRC/$1.metal" existing="$OUT/$1.rt.h"
    local out="$TMP/$name.rt.h" prefix hlslHash mslHash dxcUsed
    [ -f "$hlsl" ] && [ -f "$msl" ] || { echo "error: $name needs both $hlsl and $msl" >&2; exit 1; }
    prefix="k$(camel "$name")"
    hlslHash="$(sha256_of "$hlsl")"
    mslHash="$(sha256_of "$msl")"
    mkdir -p "$TMP/$name"
    if [ -n "$DXC" ]; then
        # -Wno-ignored-attributes: the [[vk::...]] attributes mean nothing to the DXIL compile.
        "$DXC" -T cs_6_5 -E main -Wno-ignored-attributes -Fo "$TMP/$name/dxil.bin" "$hlsl" >"$TMP/$name/dxil.log" 2>&1 ||
            { cat "$TMP/$name/dxil.log" >&2; echo "error: DXC could not compile $hlsl to DXIL" >&2; exit 1; }
        "$DXC" -spirv -fspv-target-env=vulkan1.2 -fspv-extension=SPV_KHR_ray_query -T cs_6_5 -E main \
            -Fo "$TMP/$name/spirv.bin" "$hlsl" >"$TMP/$name/spirv.log" 2>&1 ||
            { cat "$TMP/$name/spirv.log" >&2; echo "error: DXC could not compile $hlsl to SPIR-V" >&2; exit 1; }
        dxcUsed="$DXC_VERSION"
    else
        if [ ! -f "$existing" ]; then
            echo "error: $name has no committed header and no DXC is here to make its DXIL and SPIR-V: run this on Windows or Linux x86_64 after \`factoria setup dxc\`, or let the Linux CI job do it (artifact rt-shader-headers)" >&2
            exit 1
        fi
        dxcUsed="$(meta_of dxc-version "$existing")"
        hlslHash="$(meta_of hlsl-sha256 "$existing")"
        if [ "$hlslHash" != "$(sha256_of "$hlsl")" ]; then
            echo "STALE: $hlsl changed after the DXIL and SPIR-V of ${existing#"$ROOT"/} were made; the Linux CI job regenerates them (artifact rt-shader-headers)" >&2
            stale=1
        fi
    fi
    {
        printf '// Generated by tools/shaders/compile_rt_shaders.sh from engine/render/shaders/rt/%s.hlsl and %s.metal. Do not edit.\n' "$name" "$name"
        printf '// dxc-version: %s\n// hlsl-sha256: %s\n// msl-sha256: %s\n' "$dxcUsed" "$hlslHash" "$mslHash"
        printf '// dxil: DXC -T cs_6_5 (D3D12). spirv: DXC -spirv vulkan1.2 + SPV_KHR_ray_query (Vulkan). msl: the .metal text, NUL-terminated (Metal, MSL 2.4).\n'
        printf '#pragma once\n#include <cstdint>\n\nnamespace fa::rt_kernels {\n\n'
        printf 'inline constexpr const char* %sDxcVersion = "%s";\n' "$prefix" "$dxcUsed"
        printf 'inline constexpr const char* %sHlslSha256 = "%s";\n' "$prefix" "$hlslHash"
        printf 'inline constexpr const char* %sMslSha256 = "%s";\n' "$prefix" "$mslHash"
        printf 'inline constexpr const char* %sMslEntry = "%s";\n\n' "$prefix" "$name"
        if [ -n "$DXC" ]; then
            emit_blob dxil "$TMP/$name/dxil.bin" 0 "${prefix}Dxil"
            emit_blob spirv "$TMP/$name/spirv.bin" 0 "${prefix}Spirv"
        else
            section_of dxil "$existing"
            section_of spirv "$existing"
        fi
        emit_blob msl "$msl" 1 "${prefix}Msl"
        printf '\n}  // namespace fa::rt_kernels\n'
    } >"$out"
    if [ ! -f "$existing" ] || ! cmp -s "$out" "$existing"; then
        changed=1
        if [ "$CHECK" = 1 ]; then
            echo "DIFFERS: ${existing#"$ROOT"/}" >&2
        else
            mkdir -p "$OUT"
            cp "$out" "$existing"
            echo "rt: ${hlsl#"$ROOT"/} -> ${existing#"$ROOT"/}"
        fi
    else
        echo "rt: ${existing#"$ROOT"/} is up to date"
    fi
}

ran=0
for input in "$SRC"/*.hlsl; do
    [ -f "$input" ] || continue
    name="$(basename "$input" .hlsl)"
    if [ "${#NAMES[@]}" -gt 0 ] && [[ " ${NAMES[*]} " != *" $name "* ]]; then continue; fi
    generate "$name"
    ran=$((ran + 1))
done
if [ "$ran" = 0 ]; then
    echo "error: no ray tracing kernel matched (kernels: $(cd "$SRC" && ls *.hlsl 2>/dev/null | sed 's/\.hlsl$//' | tr '\n' ' '))" >&2
    exit 1
fi
if [ "$stale" = 1 ] && [ "$CHECK" = 1 ]; then exit 2; fi
if [ "$CHECK" = 1 ] && [ "$changed" = 1 ]; then
    echo "error: the committed ray tracing headers differ from what this computer generates: run tools/shaders/compile_rt_shaders.sh and commit the result" >&2
    exit 1
fi
