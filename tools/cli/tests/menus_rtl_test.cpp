fa::Json command(fa::cli::Session& session, const char* json) {
    return fa::cli::run_command_json(session.registry(), fa::Json::parse(json));
}

// Rectangle [x, y, w, h] of the widget or screen-space Text `id`.
std::vector<float> rect_of(const fa::Json& state, const std::string& id) {
    for (const fa::Json& w : state["result"]["widgets"])
        if (w["id"] == id)
            return {w["rect"][0].get<float>(), w["rect"][1].get<float>(), w["rect"][2].get<float>(),
                    w["rect"][3].get<float>()};
    FAIL("no widget " << id);
    return {};
}

// Whether the rectangles [x, y, w, h] a and b share no area (a row of buttons side by side, or a column when the row did not fit).
bool apart(const std::vector<float>& a, const std::vector<float>& b) {
    return a[0] + a[2] <= b[0] + 0.5f || b[0] + b[2] <= a[0] + 0.5f || a[1] + a[3] <= b[1] + 0.5f ||
           b[1] + b[3] <= a[1] + 0.5f;
}

