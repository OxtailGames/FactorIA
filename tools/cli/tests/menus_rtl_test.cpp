    fa::fs::set_project_root(oldRoot);

    fa::test::expect_golden_file(
        *img, fa::fs::path_from_utf8(FA_REPO_ROOT) / "tools" / "cli" / "tests" / "golden" / "menus_ar.png",
        fa::test::golden_edge_limits());  // text: glyph edges flip between GPUs
