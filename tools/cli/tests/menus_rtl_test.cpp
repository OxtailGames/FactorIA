    check_page("a mode that draws", true);
    REQUIRE(eval("Promise.all([import('scripts/settings.js'), import('factoria')]).then(([m, f]) => { "
                 "m.overrideRenderSupports((x) => x === 'dynamicResolution'); f.window.upscaler = { mode: 'metalfx' }; "
                 "return 1; })")["ok"] == true);
    engine.step(3);
    check_page("a mode drawn as stretch", false);
    REQUIRE(eval("Promise.all([import('scripts/settings.js'), import('factoria')]).then(([m, f]) => { "
                 "m.overrideRenderSupports(null); f.window.upscaler = { mode: 'stretch' }; return 1; })")["ok"] ==
            true);
    // The frame generation page's row of two page buttons ("Low latency" and "Ray tracing", 280 wide each) on the small window, with the
    // longest labels (Spanish and Arabic): both inside the section and the panel, side by side or stacked, and clear of the note above
    // and the section's end below.
    REQUIRE(eval("for (const id of ['video_section', 'graphics_section', 'quality_section', 'latency_section', "
                 "'raytracing_section', 'audio_section', 'controls_section', 'language_section']) "
                 "world.find(id).active = false; world.find('framegen_section').active = true; 1")["ok"] == true);
    engine.step(3);
    for (const char* lang : {"es", "ar", "en"}) {
        INFO("frame generation page row at 1024x642, language " << std::string(lang));
        REQUIRE(set_language(lang)["ok"] == true);
        engine.step(5);
        const fa::Json st = command(*session, R"({"command":"ui.state","args":{}})");
        REQUIRE(st["ok"] == true);
        const std::vector<float> fbox = rect_of(st, "framegen_section"), fnote = rect_of(st, "framegen_note"),
                                 nav = rect_of(st, "gfx_fg_nav"), lat = rect_of(st, "gfx_fg_back"),
                                 rt = rect_of(st, "gfx_rt_page"), froot = rect_of(st, "options");
        for (const std::vector<float>& r : {nav, lat, rt}) {
            CHECK(r[0] >= fbox[0] - 0.5f);
            CHECK(r[0] + r[2] <= fbox[0] + fbox[2] + 0.5f);
            CHECK(r[1] + r[3] <= fbox[1] + fbox[3] - 8.0f);
        }
        CHECK(apart(lat, rt));
        CHECK(fnote[1] + fnote[3] <= nav[1] + 0.5f);
        CHECK(froot[1] >= 0.0f);
        CHECK(froot[1] + froot[3] <= 642.0f);
    }
    // Every other page of the panel, with no renderer table of its own: the panel (never taller than the screen) and the Back button are on screen.
    // (The first page of the Graphics tab, graphics_section, is checked at 1280x720 above: its section is 468 high and its three notes
    // need it, so it is taller than 642.)
    for (const char* page : {"video_section", "latency_section", "framegen_section", "raytracing_section",
                             "audio_section", "controls_section", "language_section"}) {
        for (const char* lang : {"es", "ar", "en"}) {
            INFO(std::string(page) << ", language " << std::string(lang));
            REQUIRE(set_language(lang)["ok"] == true);
            REQUIRE(
                eval(std::string(
                         "for (const id of ['video_section', 'graphics_section', 'quality_section', 'latency_section', "
                         "'framegen_section', 'raytracing_section', 'audio_section', 'controls_section', "
                         "'language_section']) "
                         "world.find(id).active = id === '") +
                     page + "'; 1")["ok"] == true);
            engine.step(3);
            const fa::Json st = command(*session, R"({"command":"ui.state","args":{}})");
            REQUIRE(st["ok"] == true);
            const std::vector<float> root = rect_of(st, "options"), back = rect_of(st, "options_back");
            CHECK(root[1] >= 0.0f);
            CHECK(root[1] + root[3] <= 642.0f);
            CHECK(back[1] + back[3] <= 642.0f);
        }
    }
    fa::fs::set_project_root(oldRoot);
