ai::HttpResponse send(const std::string& url, const std::string& body, const std::string& method = "POST") {
    ai::HttpRequest r;
    r.method = method;
    r.url = url;
    r.headers = {{"content-type", "application/json"}, {"accept", "application/json, text/event-stream"}};
    r.body = body;
    r.timeoutSeconds = 20;
    r.connectTimeoutSeconds = 5;
    return ai::http_request(r);
}

// A registry with a stand-in scene.spawn, served the way the editor serves its proxy registry.
struct Endpoint {
    CommandRegistry registry;
    std::vector<std::string> spawned;
    McpHttpServer server;
    std::string url;
    explicit Endpoint(std::chrono::milliseconds streamAfter = std::chrono::seconds(10)) {
        CommandInfo i;
        i.name = "scene.spawn";
        i.summary = "Stand-in: records the name.";
        i.readOnly = false;
        i.inputSchema = Json::parse(R"({"type":"object","properties":{"name":{"type":"string","description":"Entity name."}}})");
        registry.add(i, [this](const Json& a) {
            spawned.push_back(a.value("name", std::string()));
            return Json::object({{"id", spawned.back()}});
        });
        CommandInfo w;
        w.name = "test.wait";
        w.summary = "Stand-in for a long call (ai.run): returns after 300 ms.";
        registry.add(w, [](const Json&) {
            std::this_thread::sleep_for(std::chrono::milliseconds(300));
            return Json::object();
        });
        CommandInfo p;
        p.name = "test.progress";
        p.summary = "Stand-in for ai.run: reports what it does for 400 ms.";
        registry.add(p, [](const Json&) {
            report_command_progress("worker: Bash cmake --build");
            std::this_thread::sleep_for(std::chrono::milliseconds(400));
            return Json::object();
        });
        auto started = server.start([this](std::string_view m, const McpHttpServer::Notify& notify) {
            SimpleMcpHost host(registry, ".");
            McpServer mcp(host);
            mcp.set_notification_sink([&notify](const std::string& n) { notify(n); });
            mcp.set_progress_timing(std::chrono::milliseconds(50), std::chrono::milliseconds(100));
            return mcp.handle_message(m);
        }, streamAfter);
        REQUIRE(started);
        url = *started;
    }
};

std::string read_file(const stdfs::path& p) {
    std::ifstream in(p, std::ios::binary);
    std::stringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

