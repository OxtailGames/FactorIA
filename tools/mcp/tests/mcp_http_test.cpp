std::uint16_t port_of(const std::string& url) {  // "http://127.0.0.1:<port>/mcp/<token>"
    const auto colon = url.rfind(':');
    return static_cast<std::uint16_t>(std::stoi(url.substr(colon + 1)));
}
std::string path_of(const std::string& url) { return url.substr(url.find("/mcp/")); }

// A raw client, for what an HTTP library hides: a connection that stays silent, a body that is never sent.
struct RawClient {
    net::Socket s = net::kNoSocket;
    explicit RawClient(std::uint16_t port) {
        s = net::connect_loopback(port);
        if (s != net::kNoSocket) net::set_io_timeouts(s, 30000, 30000);  // 30 s: far above any answer here
    }
    ~RawClient() { close(); }
    void close() {
        if (s != net::kNoSocket) net::close_socket(s);
        s = net::kNoSocket;
    }
    bool send(const std::string& data) const { return net::send_all(s, data); }
    // One response with a Content-Length body (the connection may stay open); "" when it ends first.
    std::string read_response() const {
        std::string out;
        char chunk[4096];
        for (;;) {
            if (const auto head = out.find("\r\n\r\n"); head != std::string::npos) {
                const auto at = out.find("Content-Length: ");
                const std::size_t length = at == std::string::npos ? 0 : std::stoul(out.substr(at + 16));
                if (out.size() >= head + 4 + length) return out;
            }
            const auto n = net::recv_some(s, chunk, sizeof chunk);
            if (n <= 0) return "";
            out.append(chunk, static_cast<std::size_t>(n));
        }
    }
    // Everything until the server closes the connection (or the 30 s timeout).
    std::string read_all() const {
        std::string out;
        char chunk[4096];
        for (;;) {
            const auto n = net::recv_some(s, chunk, sizeof chunk);
            if (n <= 0) return out;
            out.append(chunk, static_cast<std::size_t>(n));
        }
    }
    static std::string post(const std::string& path, const std::string& body, bool close = true) {
        return "POST " + path + " HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json\r\nAccept: application/json\r\n" +
               std::string(close ? "Connection: close\r\n" : "") + "Content-Length: " + std::to_string(body.size()) + "\r\n\r\n" + body;
    }
};

constexpr const char* kPing = R"({"jsonrpc":"2.0","id":1,"method":"ping"})";

