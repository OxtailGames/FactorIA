// A float literal: %.9g prints 1 for 1.0, which with an f suffix is no literal; add the point.
std::string literal(double value) {
    char text[32];
    std::snprintf(text, sizeof text, "%.9g", value);
    std::string out = text;
    if (out.find_first_of(".en") == std::string::npos) out += ".0";
    return out + "f";
}

void append_array(std::string& out, const char* name, const std::vector<float>& values, const char* doc) {
    out += "// ";
    out += doc;
    out += "\ninline constexpr float ";
    out += name;
    out += "[";
    out += std::to_string(values.size());
    out += "] = {";
    for (std::size_t i = 0; i < values.size(); ++i) {
        if (i % 8 == 0) out += "\n   ";
        out += " " + literal(static_cast<double>(values[i])) + ",";
    }
    out += "\n};\n\n";
}

